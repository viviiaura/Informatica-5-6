def main():
    # Augmented Assignment Opetator
    score = 10
    score += 10
    print(score)

    # Substraction

    # "x-=y"
    grade = 100
    grade -= 15
    print(grade)

    # Multiplication Assignment Operator
    balance = 20
    balance *= 4
    print(balance)

    #Division Assignment Operator

    x = 10
    x /= 5

    print(x)

    #Modulus Assignment Operator

    a = 10
    b = 4

    a %= b
    print(a)


if __name__== "__main__":
    main()
